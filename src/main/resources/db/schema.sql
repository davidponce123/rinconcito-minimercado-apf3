-- RINCONCITO MINIMERCADO | ESQUEMA APF3 ALINEADO CON APF2 (15 TABLAS)
-- Diseño PostgreSQL a ejecutar antes de iniciar el servidor. No ejecutado en este entorno.
-- Ejecutar sobre una base de datos de pruebas vacía; revisar permisos antes de producción.
BEGIN;

CREATE TABLE rol (
  id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE usuario (
  id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_usuario VARCHAR(40) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  id_rol INTEGER NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE administrador (
  id_usuario INTEGER PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  nivel_acceso VARCHAR(30) NOT NULL
);
CREATE TABLE cajero (
  id_usuario INTEGER PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  codigo_cajero VARCHAR(20) NOT NULL UNIQUE
);
CREATE TABLE categoria (
  id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion VARCHAR(100)
);
CREATE TABLE proveedor (
  id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE producto (
  id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  precio NUMERIC(10,2) NOT NULL CHECK(precio>=0),
  descripcion VARCHAR(120),
  id_categoria INTEGER NOT NULL REFERENCES categoria(id_categoria) ON DELETE RESTRICT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE inventario (
  id_inventario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto INTEGER NOT NULL UNIQUE REFERENCES producto(id_producto) ON DELETE RESTRICT,
  stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK(stock_minimo >= 0)
);
CREATE TABLE venta (
  id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  tipo_pago VARCHAR(30) NOT NULL CHECK(tipo_pago IN ('EFECTIVO','YAPE','PLIN','TARJETA')),
  fecha_pago TIMESTAMPTZ,
  id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  CONSTRAINT ck_fecha_pago CHECK(fecha_pago IS NULL OR fecha_pago>=fecha)
);
CREATE TABLE detalle_venta (
  id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta BIGINT NOT NULL REFERENCES venta(id_venta) ON DELETE RESTRICT,
  id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL CHECK(cantidad>0),
  precio NUMERIC(10,2) NOT NULL CHECK(precio>=0),
  CONSTRAINT uq_venta_producto UNIQUE (id_venta,id_producto)
);
CREATE TABLE ingreso_mercaderia (
  id_ingreso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  guia VARCHAR(30) NOT NULL,
  id_proveedor INTEGER NOT NULL REFERENCES proveedor(id_proveedor) ON DELETE RESTRICT,
  id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
    CHECK(estado IN ('PENDIENTE','INGRESADO')),
  CONSTRAINT uq_guia_proveedor UNIQUE(id_proveedor, guia)
);
CREATE TABLE detalle_ingreso (
  id_detalle_ingreso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ingreso BIGINT NOT NULL REFERENCES ingreso_mercaderia(id_ingreso) ON DELETE RESTRICT,
  id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL CHECK(cantidad>0),
  costo NUMERIC(10,2) NOT NULL CHECK(costo>=0),
  fecha_vencimiento DATE
  -- No UNIQUE (id_ingreso,id_producto): distintos lotes pueden vencer en fechas diferentes.
);
CREATE TABLE movimiento_inventario (
  id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('ENTRADA','SALIDA')),
  cantidad INTEGER NOT NULL CHECK(cantidad>0),
  id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
  id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  id_venta BIGINT REFERENCES venta(id_venta) ON DELETE RESTRICT,
  id_ingreso BIGINT REFERENCES ingreso_mercaderia(id_ingreso) ON DELETE RESTRICT,
  CONSTRAINT ck_origen_movimiento CHECK (
    (tipo='SALIDA' AND id_venta IS NOT NULL AND id_ingreso IS NULL)
    OR (tipo='ENTRADA' AND id_ingreso IS NOT NULL AND id_venta IS NULL)
  )
);
CREATE TABLE accion_baja_rotacion (
  id_accion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto INTEGER NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
  decision VARCHAR(40) NOT NULL,
  id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- Tabla 15 del APF2: estructura de auditoria_cambio.
-- Nota: el alta de auditoría desde operaciones Java aún requiere pruebas e integración;
-- la tabla por sí sola no constituye una auditoría activa.
CREATE TABLE auditoria_cambio (
  id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tabla_afectada VARCHAR(50) NOT NULL,
  id_registro BIGINT NOT NULL,
  accion VARCHAR(20) NOT NULL CHECK(accion IN ('INSERT','UPDATE','CAMBIO_ESTADO')),
  id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  detalle TEXT
);
CREATE INDEX idx_auditoria_usuario_fecha ON auditoria_cambio(id_usuario,fecha DESC);

-- Índices para las relaciones y consultas más habituales.
CREATE INDEX idx_venta_fecha_pago ON venta(fecha_pago) WHERE fecha_pago IS NOT NULL;
CREATE INDEX idx_detalle_venta_producto ON detalle_venta(id_producto);
CREATE INDEX idx_ingreso_fecha ON ingreso_mercaderia(fecha);
CREATE INDEX idx_detalle_ingreso_producto ON detalle_ingreso(id_producto);
CREATE INDEX idx_mov_producto_fecha ON movimiento_inventario(id_producto,fecha);
CREATE INDEX idx_mov_usuario ON movimiento_inventario(id_usuario);
CREATE INDEX idx_accion_producto_fecha ON accion_baja_rotacion(id_producto,fecha DESC);
CREATE UNIQUE INDEX uq_salida_documento_producto ON movimiento_inventario(id_venta,id_producto)
 WHERE tipo='SALIDA';
CREATE UNIQUE INDEX uq_entrada_documento_producto ON movimiento_inventario(id_ingreso,id_producto)
 WHERE tipo='ENTRADA';

-- Cálculo derivado del saldo: incluye productos todavía sin movimientos.
CREATE VIEW v_stock AS
SELECT p.id_producto, p.nombre, i.stock_minimo,
       COALESCE(SUM(CASE WHEN m.tipo='ENTRADA' THEN m.cantidad
                         WHEN m.tipo='SALIDA' THEN -m.cantidad ELSE 0 END),0) AS stock_actual
FROM producto p JOIN inventario i ON i.id_producto=p.id_producto
LEFT JOIN movimiento_inventario m ON m.id_producto=p.id_producto
GROUP BY p.id_producto,p.nombre,i.stock_minimo;

-- Las ventas pendientes se excluyen de los reportes de cobros, no se inventan totales.
CREATE VIEW v_venta_total AS
SELECT v.id_venta,v.fecha,v.fecha_pago,v.tipo_pago,v.id_usuario,
       COALESCE(SUM(d.cantidad*d.precio),0)::NUMERIC(12,2) AS total
FROM venta v LEFT JOIN detalle_venta d ON d.id_venta=v.id_venta
GROUP BY v.id_venta,v.fecha,v.fecha_pago,v.tipo_pago,v.id_usuario;
COMMIT;

